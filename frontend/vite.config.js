import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { defineConfig, loadEnv } from 'vite';
import { DEFAULT_SITE_URL, pageSeo, seoHead, siteOrigin } from './seo/site.js';
import { isIP } from 'node:net';
import react from '@vitejs/plugin-react';

// @vitejs/plugin-react was already a dependency but was never wired up, which
// meant no React Fast Refresh in development. Vite's root is this directory, so
// `public/assets/*` is still served at `/assets/*` and the `/src/main.jsx`
// reference in index.html resolves exactly as it did before the monorepo move.
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const origin = siteOrigin(process.env.VITE_SITE_URL || env.VITE_SITE_URL || DEFAULT_SITE_URL);
  if (mode === 'production' && (new URL(origin).protocol !== 'https:' || isIP(new URL(origin).hostname.replace(/^\[|\]$/g, '')))) {
    throw new Error('Production VITE_SITE_URL must be the public HTTPS domain, not a server IP');
  }
  return {
    plugins: [react(), {
      name: 'store-seo',
      async writeBundle(_options, bundle) {
        const html = bundle['index.html'];
        if (!html || html.type !== 'asset') throw new Error('Missing built HTML for SEO function');
        // Import the finished HTML as code so function tracing includes it,
        // independently of the static output directory and runtime cwd.
        await writeFile(new URL('./seo/generated-template.js', import.meta.url),
          `// Generated by Vite. Do not edit.
export default ${JSON.stringify(String(html.source))};
`);
        const offline = await readFile(new URL('./public/offline.html', import.meta.url), 'utf8');
        const appIcon = await readFile(new URL('./public/assets/pwa/icon-192.png', import.meta.url));
        const version = createHash('sha256').update(String(html.source)).update(offline).update(appIcon).digest('hex').slice(0, 12);
        const worker = await readFile(new URL('./public/sw.js', import.meta.url), 'utf8');
        await writeFile(new URL('./dist/sw.js', import.meta.url), worker.replace('__APP_VERSION__', version));
      },
      transformIndexHtml(html) {
        return html.replace(/<!-- SEO_START -->[\s\S]*?<!-- SEO_END -->/, `<!-- SEO_START -->${seoHead(pageSeo({ origin }))}<!-- SEO_END -->`);
      },
    }],
    server: {
      port: 5173,
    },
  };
});
